/**
 * 一段对话的叫法。
 *
 * 并排几段对话时，几行都写着「新的对话」是没法指认的：说「左边那个」靠位置，位置
 * 一会就变了；说「对话 2」靠顺序，关掉一段之后序号全是错的。给每段一个自己带着的
 * 名字，是可以被念出来、被记住、也不随布局变化的。名字从会话 id 折出来，所以刷新
 * 之后还是同一个——它是这段对话的身份，不是这次渲染的编号。
 *
 * 折法只用 id 本身：不带时间、不带随机数。同一个 id 在任何一台打开的界面上都念作
 * 同一个名字，读者在另一台机器上看到的名字与这里一致。
 */

/** 人名字，都是寻常的写法——它要能被念出来、能在标题行里放得下。 */
const NAMES = [
  '明远',
  '静怡',
  '文博',
  '清和',
  '宁远',
  '嘉禾',
  '正阳',
  '和顺',
  '青云',
  '思齐',
  '若谷',
  '怀安',
  '立诚',
  '安然',
  '晓光',
  '远航',
];

/** FNV-1a：一段短字符串折成一个稳定的数，不需要密码学性质。 */
function hash(id: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < id.length; i += 1) {
    h ^= id.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

/**
 * `明远·3f2`：一个名字加三位十六进制。
 *
 * 三位不是两位数顺手多敲一下：名字要指认的是同一个人，认错就是认错一段对话。
 * 十六个名字配两位十六进制只有 4096 种组合，并排十几段时撞名的概率已经不小；
 * 三位是六万多，同一个人从十六个名字里抽一个，撞名基本不发生。
 */
export function callsignOf(sessionId: string): string {
  const h = hash(sessionId);
  const name = NAMES[h % NAMES.length];
  return `${name}·${(h >>> 12).toString(16).padStart(3, '0').slice(-3)}`;
}
