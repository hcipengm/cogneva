//! 两本账（变更账、原则账）折叠时的三个节流：一起看多少、一轮折多少、量不到的多
//! 久后再试。
//!
//! 两本账问的是同一个问题——「一轮折叠摊多开」——曾经各自写着同样的数（peek 50、
//! 每轮 200、量不到的重试 3600 秒）：同一件事两个答案，改一处那天就不一样了。

use std::time::Duration;

/// 只为让「账读得到、还有多少没做」成为一行日志：peek 取够看就行，不是工作清单。
// cap: fixed — 只给日志一行看的 peek，不是工作清单；真正的批量由做活那一轮按自己的节流取
// keep: 删掉后日志一行要打整份工作清单；由「只给日志一行看的 peek」兜住
pub const OUTSTANDING_PEEK: usize = 50;

/// 一轮折叠取多少条。行的代价是延迟不是覆盖面：最旧的下一轮接着取，剩下的照样被扫到。
// cap: fixed — 行的代价是延迟不是覆盖面：最旧的行下一轮接着取，剩下的照样被扫到
// keep: 删掉后一拍取行无界，最旧的行等不到下一轮；由「最旧的行下一轮接着取」兜住
// not-a-bound: 单位换算（定义性常量：改它只改单位，不改任何阈值行为）
pub const MEASUREMENTS_PER_PASS: usize = 200;

/// 一条量不到的行隔多久再问：长到一次几小时的扫描不会把它重刷一遍，又短到改过的
/// 树在同一个工作时段内被注意到。
// cap: fixed — 长到一次几小时的扫描不会把它重刷一遍，又短到改过的树在同一个工作时段内被注意到
// keep: 删掉后几小时的扫描把同一个不可测重刷一遍；由「同一个工作时段内被注意到」兜住
pub const UNMEASURABLE_RETRY: Duration = Duration::from_secs(3600);
