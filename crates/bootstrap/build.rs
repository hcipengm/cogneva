//! 构建期把部署资产（预渲染清单、init-secrets 脚本、helm chart）打进二进制，
//! 让预编译引导器不依赖源码树即可完成 apply/helm 两条投递路径。
//!
//! 生成 $OUT_DIR/bootstrap_assets.rs，内容为 (相对仓库根路径, include_bytes!)
//! 列表；运行时解包到临时工作目录并把 COGNEVA_REPO_ROOT 指过去，既有磁盘
//! 路径逻辑保持不变。

use std::fs;
use std::path::{Path, PathBuf};

#[path = "../cogneva/tests/common/root.rs"]
mod root;

use root::{rendered_root, repo_root};

fn main() {
    let repo_root = repo_root();
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());

    // 渲染产物不进仓：构建这一刻从 chart 现场生成。引导器在**部署时**不能跑 helm
    // （命门链路零下载），所以生成必须落在这里；打进二进制的就是刚生成的字节。
    //
    // 只给 Linux 目标：交付面是 Linux 集群（K3s/buildah），别的平台这一份只证明
    // 编得过（CI 的三平台矩阵），内嵌一份自己交付不了的清单只会让二进制里多出
    // 一份永远没人读的字节。判**目标平台**而不是「这台机器装没装 helm」——按环境
    // 判会让同一个提交在两台机器上编出不同的二进制，而那份差异没有东西量。
    let linux_target = std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("linux");
    let rendered = if linux_target {
        // 渲染产物的输入变了要重跑这份构建脚本：目录级声明会递归盯住 chart 整棵树，
        // 渲染链的脚本和额度基线各点一处。不声明就会拿着一份上一版的产物编译，
        // 而「没重渲染」与「chart 没变」在产物上同形。
        for rel in [
            "deploy/helm/cogneva",
            "deploy/scripts/render-deploy.sh",
            "deploy/scripts/render-chart.sh",
            "deploy/scripts/project-resource-governance.py",
            "deploy/scripts/check-governance-consistency.sh",
            "deploy/scripts/lib/rendered-cache.sh",
            "deploy/k3s/resource-quota.yaml",
        ] {
            println!("cargo:rerun-if-changed={}", repo_root.join(rel).display());
        }
        Some(rendered_root())
    } else {
        None
    };

    // (相对仓库根的路径, 是否递归目录)
    let asset_roots: &[(&str, bool)] = &[
        ("deploy/rendered/k3s-single", true),
        ("deploy/rendered/k3s-multi", true),
        ("deploy/rendered/k8s-standard", true),
        ("deploy/scripts/init-secrets.sh", false),
        ("deploy/helm/cogneva", true),
    ];

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    for (rel, recursive) in asset_roots {
        // 预渲染那三棵从刚生成的树里取，其余从仓里取；写进产物的相对名不变，
        // 运行时的解包路径因此一个字节都不用改。
        let abs = match rel.strip_prefix("deploy/rendered/") {
            // 非 Linux 目标不内嵌交付清单（理由见上）。
            Some(_) if rendered.is_none() => continue,
            Some(rest) => rendered.as_ref().unwrap().join(rest),
            None => repo_root.join(rel),
        };
        if *recursive {
            collect_files(&repo_root, &abs, &mut entries);
        } else {
            entries.push((rel.to_string(), abs));
        }
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let mut generated = String::from(
        "// Auto-generated by crates/bootstrap/build.rs — do not edit.\n\
         pub const EMBEDDED_ASSETS: &[(&str, &[u8])] = &[\n",
    );
    for (rel, abs) in &entries {
        // 逐文件声明 rerun-if-changed：目录级声明感知不到深层文件的内容变化
        println!("cargo:rerun-if-changed={}", abs.display());
        let path = abs.to_string_lossy().replace('\\', "/");
        let rel = rel.replace('\\', "/");
        generated.push_str(&format!("    ({rel:?}, include_bytes!({path:?})),\n"));
    }
    generated.push_str("];\n");
    fs::write(out_dir.join("bootstrap_assets.rs"), generated).unwrap();
}

fn collect_files(repo_root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let entries =
        fs::read_dir(dir).unwrap_or_else(|e| panic!("读取资产目录 {} 失败: {e}", dir.display()));
    for entry in entries {
        let entry = entry.unwrap();
        let path = entry.path();
        if path.is_dir() {
            collect_files(repo_root, &path, out);
            continue;
        }
        // 点文件不是资产：render-deploy.sh 中途失败会残留 .rendered.yaml 这类中间产物，
        // 一旦被打进 include_bytes!，源文件随后消失就会让整个 workspace 编译不过。
        let hidden = path
            .file_name()
            .map(|n| n.to_string_lossy().starts_with('.'))
            .unwrap_or(false);
        if hidden {
            continue;
        }
        let rel = path.strip_prefix(repo_root).unwrap().to_path_buf();
        out.push((rel.to_string_lossy().replace('\\', "/"), path));
    }
}
