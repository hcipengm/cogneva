//! 订阅失败后隔多久再订一次。
//!
//! 一条总线的消费者有四个（就绪队列、DAG 事件流、监督器的多后端消费者、记忆的
//! 入站）：它们问的是同一个问题——后端没回来时该等多久再试。曾经四处各写一个
//! 5s：平时四个答案一样，改一处那天就不一样了，而读的人看不出是哪一层不一致。

use std::time::Duration;

/// 一次失败的订阅在这个间隔后重试。
///
/// 后端要么回来要么不回来：更快的重试只会在集群已经不健康时成倍放大告警，更慢的
/// 重试会让恢复多等一个周期。
// cap: fixed — 四个消费者共用的同一条：后端要么回来要么不回来，更快的重试只在集群已经不健康时成倍放大告警
// keep: 删掉后四个消费者各用一条退避，重试在集群不健康时成倍放大告警；由「共用同一条」兜住
pub const SUBSCRIBE_RETRY_BACKOFF: Duration = Duration::from_secs(5);
