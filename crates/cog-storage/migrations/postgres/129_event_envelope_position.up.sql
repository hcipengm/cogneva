-- 信封补两列：全局单调位点与入库时刻。
--
-- `at` 是这件事**发生**的时刻（可能由上游/重放带来）；`recorded_at` 是它**进库**
-- 的时刻（服务端钟）。两者分开，才能回答「这一条晚到了多久」；合成一格时重放会
-- 把历史事件伪装成刚发生。
--
-- `seq` 是跨 kind 的全局位点：读「某某之后的所有事件」用它，而不是拿 `at` 排序
-- ——同一毫秒里的多条事件在 `at` 上没有先后，而位点有。
ALTER TABLE cogneva_event
    ADD COLUMN IF NOT EXISTS seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN IF NOT EXISTS recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

CREATE UNIQUE INDEX IF NOT EXISTS idx_cogneva_event_seq ON cogneva_event(seq);
CREATE INDEX IF NOT EXISTS idx_cogneva_event_recorded_at ON cogneva_event(recorded_at);
