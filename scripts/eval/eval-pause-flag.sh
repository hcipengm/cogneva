#!/usr/bin/env bash
# 评测的总开关，只有这一个定义处。
#
# 在这一份出现之前，「关掉评测」等于在宿主上杀掉三条进程，而拉起它们的那条腿
# （`eval-supervisor-ensure.sh`，由用户级定时器每十分钟跑一次）会在十分钟内把值守
# 重新拉起来。2026-11-08 实测：上午手工停掉的那一轮，两小时三十二分钟后已经在自己
# 跑了，没有人知道它是什么时候回来的。开关存在磁盘上，不活在进程里，因为要被关掉的
# 恰恰是「会自己回来的东西」。
#
# 三条入口都 source 这一份，而不是各自写一遍默认路径：三份默认路径里改了任一份，
# 另外两条就还在读旧位置，而那时候的读数看起来完全正常——关着的东西照跑。
#
# 被 source 使用，不单独执行。
PAUSE_FLAG=${PAUSE_FLAG:-$HOME/eval-runs/.runner/paused}

# 开关关着吗。判据只有「这个文件在不在」，不看内容：内容是人写的理由，读它会让
# 一台写坏了的机器（空文件、半行）变成「开着」。
eval_paused() { [ -e "$PAUSE_FLAG" ]; }
