_TOPOLOGY_RE = re.compile(r"(?m)^# topology-nodes: ([0-9]+)$")


def refuse(message):
    """拿不到拓扑是「这一跑没判成」（2），不是漂移，也不是通过。"""
    print(message, file=sys.stderr)
    sys.exit(2)


def recorded_nodes(path):
    """生成文件首部记下的拓扑。`--check` 在无集群的 CI 上按它重算。"""
    with open(path) as fh:
        m = _TOPOLOGY_RE.search(fh.read())
    if not m:
        refuse(
            f"{path} 首部没有 `# topology-nodes: N`：它不是投影产物，或还是旧格式。"
            f"拿不到拓扑就按它重算不了，去连得上目标集群的检出上重跑 "
            f"deploy/scripts/render-deploy.sh"
        )
    return int(m.group(1))


def live_nodes():
    """DaemonSet 逐节点铺开后有几分 Pod：只有 live cluster 知道。"""
    kubectl = shlex.split(os.environ.get("COGNEVA_KUBECTL", "sudo -n k3s kubectl"))
    try:
        out = subprocess.run(
            kubectl + ["get", "nodes", "-o", "json"],
            capture_output=True,
            text=True,
            check=True,
        )
        items = (json.loads(out.stdout) or {}).get("items") or []
    except (OSError, subprocess.CalledProcessError, json.JSONDecodeError) as exc:
        refuse(
            f"读不到 live cluster 的节点数（COGNEVA_KUBECTL={' '.join(kubectl)}）："
            "DaemonSet 的副本数就是它，额度必须按拓扑算。没有集群时用 `--nodes N`"
            "（或 COGNEVA_NODES=N）显式给拓扑；`--check` 用 `--nodes-from <生成文件>`"
            f"读上次记录的拓扑。不猜一个 1。原始错误：{exc}"
        )
    if not items:
        refuse(
            "live cluster 报 0 个节点：这份拓扑下没有任何 Pod 会落地，额度算不成。"
            "先查集群，不要把它当成 1"
        )
    return len(items)


def resolve_nodes(explicit, from_file):
    """`--nodes` > `--nodes-from` > `COGNEVA_NODES` > live cluster。

    顺序里没有任何一环会回落到 1：猜 1 与"真只有 1 个节点"在产物上完全同形，
    而前者会让多节点集群收到一份逐节点铺不开的额度。
    """
    if explicit is not None:
        nodes = int(explicit)
    elif from_file:
        nodes = recorded_nodes(from_file)
    elif os.environ.get("COGNEVA_NODES"):
        nodes = int(os.environ["COGNEVA_NODES"])
    else:
        nodes = live_nodes()
    if nodes < 1:
        refuse(f"节点数是 {nodes}：DaemonSet 至少要在一个节点上铺开，这份拓扑不算额度")
    return nodes


def governance_inputs(values_path, profile_path):
    """chart values 与 profile 里的 LimitRange 策略。

    LimitRange 的默认值/上下限是量纲上的策略（最小 10m 是 K8s 的取整步长，
    最大那份贴着渲染集里最大的容器声明），不是这套清单的函数，所以它们仍是
    输入；节点数不在这里，见 `resolve_nodes`。
    """
    def load(path):
        if not path:
            return {}
        with open(path) as fh:
            return yaml.safe_load(fh) or {}

    merged = {}
    for src in (load(values_path), load(profile_path)):
        gov = src.get("resourceGovernance") if isinstance(src, dict) else None
        if not isinstance(gov, dict):
            continue
        for key, val in gov.items():
            if isinstance(val, dict):
                merged.setdefault(key, {}).update(val)
            else:
                merged[key] = val
    limit_range = merged.get("limitRange") or {}
    return {
        "default_cpu": limit_range.get("defaultCpu", "500m"),
        "default_memory": limit_range.get("defaultMemory", "512Mi"),
        "default_request_cpu": limit_range.get("defaultRequestCpu", "50m"),
        "default_request_memory": limit_range.get("defaultRequestMemory", "64Mi"),
        "min_cpu": limit_range.get("minCpu", "10m"),
        "min_memory": limit_range.get("minMemory", "16Mi"),
        "pvc_min": limit_range.get("pvcMinStorage", "1Gi"),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rendered", required=True, help="渲染产物目录或单个 YAML")
    ap.add_argument(
        "--values", help="chart values.yaml（读 LimitRange 默认值/上下限）"
    )
    ap.add_argument("--profile", help="profile values（读 LimitRange 覆盖）")
    ap.add_argument("--nodes", type=int, help="拓扑：节点数（离线渲染时显式给）")
    ap.add_argument(
        "--nodes-from", help="拓扑：从这份生成文件首部的 `# topology-nodes:` 读"
    )
    ap.add_argument("--write-values")
    ap.add_argument("--write-quota")
    ap.add_argument("--default-cpu")
    ap.add_argument("--default-memory")
    ap.add_argument("--default-request-cpu")
    ap.add_argument("--default-request-memory")
    ap.add_argument("--min-cpu")
    ap.add_argument("--min-memory")
    ap.add_argument("--pvc-min")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    declared = governance_inputs(args.values, args.profile)
    nodes = resolve_nodes(args.nodes, args.nodes_from)
    for name in ("default_cpu", "default_memory", "default_request_cpu",
                 "default_request_memory", "min_cpu", "min_memory", "pvc_min"):
        if getattr(args, name) is None:
            setattr(args, name, declared[name])

    docs = render_docs(args.rendered)
    p = project(
        docs,
        nodes,
        default_cpu=args.default_cpu,
        default_memory=args.default_memory,
        pvc_min=args.pvc_min,
    )
    p.update(
        {
            "_nodes": nodes,
            "_runtime_cpu": fmt_cpu(0),
            "_runtime_mem": fmt_mem(0),
            "_default_cpu": args.default_cpu,
            "_default_mem": args.default_memory,
            "_default_request_cpu": args.default_request_cpu,
            "_default_request_mem": args.default_request_memory,
            "_min_cpu": args.min_cpu,
            "_min_mem": args.min_memory,
            "_pvc_min": args.pvc_min,
        }
    )

    targets = []
    if args.write_values:
        targets.append((args.write_values, values_document(p)))
    if args.write_quota:
        targets.append((args.write_quota, quota_document(p)))

    if args.check:
        # 零份比对与「两份都与渲染集一致」印的是同一句话。`--check` 单独跑（没给
        # --write-values/--write-quota）时 targets 是空表，下面的循环一次也不进，
        # drift 自然是空的，于是这一跑什么都没证明却印 OK。判 3：没判成，不是通过。
        if not targets:
            print(
                "FAIL: --check 没有可比对的投影产物：既没给 --write-values 也没给 "
                "--write-quota，零份文件与「全部一致」在输出上同形",
                file=sys.stderr,
            )
            return 3
        drift = []
        for path, text in targets:
            if not os.path.exists(path):
                drift.append(f"{path}: 不存在（投影产物没生成）")
                continue
            current = open(path).read()
            if current != text:
                drift.append(f"{path}: 与投影不一致（改工作负载后没重新投影，或被人手改了）")
        if drift:
            for line in drift:
                print(f"FAIL: {line}", file=sys.stderr)
            print(
                "      重跑 bash deploy/scripts/render-deploy.sh 会让投影重算并写回。",
                file=sys.stderr,
            )
            return 1
        if not args.quiet:
            print("GOVERNANCE PROJECTION OK：额度与渲染集一致")
        return 0

    for path, text in targets:
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        with open(path, "w") as fh:
            fh.write(text)
    if not args.quiet:
        d = p["_detail"]
        print(
            "GOVERNANCE PROJECTION: "
            f"limits {p['limitsCpu']} 核 / {p['limitsMemory']} "
            f"（渲染集声明和 + Job + 重叠 = {p['limitsCpu']}；"
            f"替运行期 Pod 留 {p['_runtime_cpu']}——产品自建的那类自行抬额度），"
            f"拓扑 {p['_nodes']} 节点，"
            f"requests {p['requestsCpu']} 核 / {p['requestsMemory']}，"
            f"pods {p['pods']}，"
            # 声明和一起印：额度的稳态占比只有两个变量（额度、声明和），少印一个，
            # 读的人就得自己把渲染集再求和一遍才能说「这个余量够不够」。
            f"storage {p['requestsStorage']}"
            f"（声明和 {d['storage'] / (1024**3):.2f}GiB，余量 {STORAGE_HEADROOM:g}×）"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
