def values_document(p):
    return generated_header(p["_nodes"]) + (
        "resourceGovernance:\n"
        "  quota:\n"
        f'    requestsCpu: "{p["requestsCpu"]}"\n'
        f"    requestsMemory: {p['requestsMemory']}\n"
        f'    limitsCpu: "{p["limitsCpu"]}"\n'
        f"    limitsMemory: {p['limitsMemory']}\n"
        f'    pods: "{p["pods"]}"\n'
        f"    requestsStorage: {p['requestsStorage']}\n"
        # 产品自己按需建的 Pod（评测台）在创建前把自己那份形状加到配额上、结束
        # 再减回去，所以额度的声明里替它们留的是 0——不是"没有这类 Pod"，而是
        # "它们不靠声明里的余量活着"。剩下要在这里声明的是**别人**（运维临时
        # Pod 等）建的那类：它们同样记在这只配额的 used 上，却没有谁替它们抬额度。
        # 没有这类 Pod 时写成 0，而不是省略——缺注解与 0 在判词里不是一回事。
        "  runtimeSum:\n"
        f'    limitsCpu: "{p["_runtime_cpu"]}"\n'
        f"    limitsMemory: {p['_runtime_mem']}\n"
        "  limitRange:\n"
        f'    maxCpu: "{p["maxCpu"]}"\n'
        f"    maxMemory: {p['maxMemory']}\n"
        f"    pvcMaxStorage: {p['pvcMaxStorage']}\n"
    )


