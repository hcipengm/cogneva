def generated_header(nodes):
    return (
        "# GENERATED by deploy/scripts/project-resource-governance.py — DO NOT EDIT.\n"
        "# 输入：渲染集里各工作负载自己的声明（容器 limits/requests、副本数、滚动策略、\n"
        "#       PVC 声明）＋ DaemonSet 逐节点铺开时的节点数。输出：这套清单必须为\n"
        "#       自己留出的额度。换一套工作负载，这份数跟着变——它不描述任何一台机器。\n"
        f"# topology-nodes: {nodes}\n"
        "# ↑ 节点数取自渲染时连着的那个集群。没有集群的 --check 按这一行重算，所以它\n"
        "#   与下面那些数同属这份产物：拓扑变了，要在一份连得上目标集群的检出上重渲染。\n"
    )

# 存储额度的余量。它同时受两个约束，而这两个约束要的是同一个方向：
#   1) 必须大于 1——额度与声明和相等时，任何一条卷声明调大都要先改额度才装得进去；
#   2) 必须大于 1/0.9——kube-prometheus-stack 自带的 KubeQuotaAlmostFull 在
#      used/hard 过 0.9 时报警，而这个额度的**稳态 used 就是 PVC 声明和本身**
#      （准入按声明记，声明多少就占多少）。余量给 1.1 时稳态占比正好是 0.909，
#      那盏灯从装机那一刻起就是红的：2026-10-30 现网实测 requests.storage
#      391Gi/430Gi＝90.9%，把「额度没留够」与「额度一直贴着报警线」两件事绑成了
#      一个常数。1.25 把稳态压到 0.80，两件事各归各位。
STORAGE_HEADROOM = 1.25
# 上游那盏灯的阈值。这里抄的是它的判据而不是它的名字：余量与它的关系由
# `tests/project-resource-governance.test.sh` 判，改小余量会在那一格红。
QUOTA_ALERT_RATIO = 0.9

# ── 量纲 ─────────────────────────────────────────────────────────────────────

_CPU_RE = re.compile(r"^([0-9.]+)(m?)$")
_MEM_SUFFIX = {
    "": 1,
    "k": 1000,
    "K": 1000,
    "M": 1000**2,
    "G": 1000**3,
    "T": 1000**4,
    "P": 1000**5,
    "E": 1000**6,
    "Ki": 1024,
    "Mi": 1024**2,
    "Gi": 1024**3,
    "Ti": 1024**4,
    "Pi": 1024**5,
    "Ei": 1024**6,
}


def cpu_cores(value):
    """`"4"`→4.0，`"500m"`→0.5。空/缺省按 0。"""
    if value is None:
        return 0.0
    text = str(value).strip()
    if not text:
        return 0.0
    m = _CPU_RE.match(text)
    if not m:
        raise ValueError(f"认不出的 CPU 量：{value!r}")
    number, suffix = m.group(1), m.group(2)
    return float(number) / 1000.0 if suffix == "m" else float(number)


def mem_bytes(value):
    """`"512Mi"`→字节数。空/缺省按 0。"""
    if value is None:
        return 0
    text = str(value).strip()
    if not text:
        return 0
    m = re.match(r"^([0-9.]+)([A-Za-z]*)$", text)
    if not m or m.group(2) not in _MEM_SUFFIX:
        raise ValueError(f"认不出的内存量：{value!r}")
    return int(float(m.group(1)) * _MEM_SUFFIX[m.group(2)])


def fmt_cpu(cores):
    """向上取整到整数核；整数核之外不要小数（额度是准入面，小数点后面没有意义）。"""
    return str(int(math.ceil(cores - 1e-9)))


def fmt_mem(nbytes):
    """向上取整到整 GiB。"""
    gib = math.ceil(nbytes / (1024**3) - 1e-9)
    return f"{gib}Gi"


