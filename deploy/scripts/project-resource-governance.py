#!/usr/bin/env python3
"""把命名空间额度从渲染集里投影出来，而不是由人写进 values。

为什么是投影而不是标定
----------------------
命名空间额度（ResourceQuota 的 hard、LimitRange 的每容器/每卷上限）不是环境
参数，是**这套清单自己的函数**：容器声明了多大、副本有几个、滚动时同时存在几个
Pod、PVC 声明了多少——额度必须装得下这些，一个字节也不用多。同一条算式在人手
写下来的两份文件里（chart values 与 deploy/k3s 基线）已经漂过两次，漂的形态都是
「工作负载长大了，额度没跟」：准入先拒掉下一次滚动，现场读起来却是「这一版永远
滚不上去」。所以这里把它做成算出来的：输入是渲染集，输出是额度，换一套工作负载
额度自己就变。

渲染集里没有的只有两类，它们作为显式输入参与算式：`runtimeWorkloads`（运行期
由产品自己建的 Pod——评测台起一台跑一道题，它没有清单进渲染集，所以形状在 chart
values 里声明一次，这里按与渲染集完全相同的一条算式把它加进额度，而不是另写一份
"留多少核"的预算）与 `clusterNodes`（DaemonSet 逐节点铺开后有几分 Pod，由
profile 给——同一份清单既可能装在单节点 K3s 上，也可能装在 N 节点集群上）。

口径
----
- 每个 Pod 的占用取 `max(Σ 业务容器, max init 容器)`，与 kubelet 的记账一致。
- 副本数：Deployment/StatefulSet 取 `spec.replicas`（缺省 1）；DaemonSet 取
  集群节点数；Job/CronJob 取 `parallelism`（缺省 1）。
- 替换重叠：滚动更新的 Deployment 会同时存在 `maxSurge` 个新 Pod 与旧 Pod，
  额度必须容得下**最大的一份**（滚动一次只有一个 Deployment 在滚）。
- 声明和之外没有任何余量：向上取整到整数核 / 整 GiB 就是那点余量。

用法
----
  python3 project-resource-governance.py --rendered <目录或单个 YAML> \\
      --values deploy/helm/cogneva/values.yaml \\
      --profile deploy/helm/cogneva/profiles/<profile>.yaml \\
      [--write-values FILE] [--write-quota FILE] [--check]

`--values` 与 `--profile` 是算不出来的那几项的来源（运行期 Pod 的形状、节点数、
LimitRange 策略）。`--nodes`／`--default-*`／`--min-*`／`--pvc-min` 可以逐项覆盖，
不传就用文件里的值——默认留空正是为了让它们只有一个来源。

`--check` 只比不写：目标文件与投影不一致就退 1（渲染新鲜度门禁用它）。
"""

import argparse
import math
import os
import re
import sys

try:
    import yaml
except ImportError:  # pragma: no cover - 与 render-deploy.sh 同一依赖
    sys.exit("需要 python3-yaml（与 render-deploy.sh 同一依赖）")

GENERATED_HEADER = (
    "# GENERATED by deploy/scripts/project-resource-governance.py — DO NOT EDIT.\n"
    "# 输入：渲染集里各工作负载自己的声明（容器 limits/requests、副本数、滚动策略、\n"
    "#       PVC 声明）＋运行集之外那些 Pod 自己声明的形状。输出：这套清单必须为\n"
    "#       自己留出的额度。换一套工作负载，这份数跟着变——它不描述任何一台机器。\n"
)

# ── 量纲 ─────────────────────────────────────────────────────────────────────

_CPU_RE = re.compile(r"^([0-9.]+)(m?)$")
_MEM_SUFFIX = {
    "": 1,
    "k": 1000,
    "K": 1000,
    "M": 1000**2,
    "G": 1000**3,
    "T": 1000**4,
    "P": 1000**5,
    "E": 1000**6,
    "Ki": 1024,
    "Mi": 1024**2,
    "Gi": 1024**3,
    "Ti": 1024**4,
    "Pi": 1024**5,
    "Ei": 1024**6,
}


def cpu_cores(value):
    """`"4"`→4.0，`"500m"`→0.5。空/缺省按 0。"""
    if value is None:
        return 0.0
    text = str(value).strip()
    if not text:
        return 0.0
    m = _CPU_RE.match(text)
    if not m:
        raise ValueError(f"认不出的 CPU 量：{value!r}")
    number, suffix = m.group(1), m.group(2)
    return float(number) / 1000.0 if suffix == "m" else float(number)


def mem_bytes(value):
    """`"512Mi"`→字节数。空/缺省按 0。"""
    if value is None:
        return 0
    text = str(value).strip()
    if not text:
        return 0
    m = re.match(r"^([0-9.]+)([A-Za-z]*)$", text)
    if not m or m.group(2) not in _MEM_SUFFIX:
        raise ValueError(f"认不出的内存量：{value!r}")
    return int(float(m.group(1)) * _MEM_SUFFIX[m.group(2)])


def fmt_cpu(cores):
    """向上取整到整数核；整数核之外不要小数（额度是准入面，小数点后面没有意义）。"""
    return str(int(math.ceil(cores - 1e-9)))


def fmt_mem(nbytes):
    """向上取整到整 GiB。"""
    gib = math.ceil(nbytes / (1024**3) - 1e-9)
    return f"{gib}Gi"


# ── 渲染集 ───────────────────────────────────────────────────────────────────


def load_docs(paths):
    docs = []
    for path in paths:
        with open(path) as fh:
            for doc in yaml.safe_load_all(fh):
                if isinstance(doc, dict) and doc.get("kind"):
                    doc["__path__"] = path
                    docs.append(doc)
    return docs


def render_docs(rendered):
    if os.path.isdir(rendered):
        paths = sorted(
            os.path.join(rendered, n) for n in os.listdir(rendered) if n.endswith(".yaml")
        )
    else:
        paths = [rendered]
    return load_docs(paths)


def pod_footprint(spec):
    """一个 Pod 的 (requests.cpu, requests.mem, limits.cpu, limits.mem)。

    与 kubelet 的记账同一口径：业务容器求和，init 容器取最大值，两者再取大者。
    """
    pod = spec.get("template", {}).get("spec") or {}

    def tally(containers):
        cpu_r = cpu_l = 0.0
        mem_r = mem_l = 0
        for c in containers:
            res = c.get("resources") or {}
            req = res.get("requests") or {}
            lim = res.get("limits") or {}
            cpu_r += cpu_cores(req.get("cpu"))
            mem_r += mem_bytes(req.get("memory"))
            cpu_l += cpu_cores(lim.get("cpu"))
            mem_l += mem_bytes(lim.get("memory"))
        return cpu_r, mem_r, cpu_l, mem_l

    (c_r, m_r, c_l, m_l) = tally(pod.get("containers") or [])
    (i_r, im_r, i_l, im_l) = tally(pod.get("initContainers") or [])
    return (
        max(c_r, i_r),
        max(m_r, im_r),
        max(c_l, i_l),
        max(m_l, im_l),
    )


def surge_extra(doc, replicas):
    """一次滚动要多占几份 Pod（maxSurge 的控制器取整口径）。"""
    spec = doc.get("spec") or {}
    strategy = spec.get("strategy") or {}
    if strategy.get("type", "RollingUpdate") != "RollingUpdate":
        return 0
    raw = str((strategy.get("rollingUpdate") or {}).get("maxSurge", "25%"))
    if raw.endswith("%"):
        return int(-(-(float(raw[:-1]) * replicas) // 100))
    return int(raw)


def declared_workloads(docs, nodes):
    """(副本数, Pod 占用, 滚动重叠份数) 的逐对象清单。"""
    rows = []
    for doc in docs:
        kind = doc.get("kind")
        if kind not in ("Deployment", "StatefulSet", "DaemonSet", "Job", "CronJob"):
            continue
        spec = doc.get("spec") or {}
        if kind == "DaemonSet":
            replicas = nodes
        elif kind == "Job":
            replicas = int(spec.get("parallelism") or 1)
        elif kind == "CronJob":
            job = spec.get("jobTemplate", {}).get("spec") or {}
            replicas = int(job.get("parallelism") or 1)
        else:
            replicas = int(spec.get("replicas", 1) or 0)
        pod_spec = spec
        if kind == "CronJob":
            pod_spec = spec.get("jobTemplate", {}).get("spec") or {}
        cpu_r, mem_r, cpu_l, mem_l = pod_footprint(pod_spec)
        surge = surge_extra(doc, replicas) if kind == "Deployment" else 0
        rows.append(
            {
                "name": doc.get("metadata", {}).get("name", "?"),
                "kind": kind,
                "replicas": replicas,
                "requests_cpu": cpu_r,
                "requests_mem": mem_r,
                "limits_cpu": cpu_l,
                "limits_mem": mem_l,
                "surge": surge,
            }
        )
    return rows


def pvc_bytes(docs):
    total = 0
    largest = 0
    for doc in docs:
        kind = doc.get("kind")
        if kind == "PersistentVolumeClaim":
            spec = doc.get("spec") or {}
            want = mem_bytes(
                ((spec.get("resources") or {}).get("requests") or {}).get("storage")
            )
        elif kind == "StatefulSet":
            want = 0
            for tpl in (doc.get("spec") or {}).get("volumeClaimTemplates") or []:
                want += mem_bytes(
                    (((tpl.get("spec") or {}).get("resources") or {}).get("requests") or {}).get(
                        "storage"
                    )
                )
        else:
            continue
        total += want
        largest = max(largest, want)
    return total, largest


def largest_container(docs):
    """全表最大的那份单容器声明：LimitRange 的上限必须 ≥ 它，否则该 Pod 进不来。"""
    cpu = 0.0
    mem = 0
    for doc in docs:
        spec = doc.get("spec") or {}
        if doc.get("kind") == "CronJob":
            spec = spec.get("jobTemplate", {}).get("spec") or {}
        pod = spec.get("template", {}).get("spec") or {}
        for c in (pod.get("containers") or []) + (pod.get("initContainers") or []):
            res = c.get("resources") or {}
            lim = res.get("limits") or {}
            cpu = max(cpu, cpu_cores(lim.get("cpu")))
            mem = max(mem, mem_bytes(lim.get("memory")))
    return cpu, mem


def _find(docs, kind, name):
    for doc in docs:
        if doc.get("kind") == kind and (doc.get("metadata") or {}).get("name") == name:
            return doc
    return None


def deployer_job_size(docs):
    """部署器判据 Job 的尺寸：它在集群里由代码建，声明在进化侧的 configmap 里。"""
    cm = _find(docs, "ConfigMap", "cogneva-evolution-config")
    data = (cm or {}).get("data") or {}
    return {
        "limits_cpu": cpu_cores(data.get("COGNEVA_MAINLINE_DEPLOYER_ROLLOUT_JOB_CPU_LIMIT")),
        "limits_mem": mem_bytes(data.get("COGNEVA_MAINLINE_DEPLOYER_ROLLOUT_JOB_MEMORY_LIMIT")),
        "requests_cpu": cpu_cores(
            data.get("COGNEVA_MAINLINE_DEPLOYER_ROLLOUT_JOB_CPU_REQUEST")
        ),
        "requests_mem": mem_bytes(
            data.get("COGNEVA_MAINLINE_DEPLOYER_ROLLOUT_JOB_MEMORY_REQUEST")
        ),
    }


def runtime_rows(entries):
    """渲染集之外、运行期按需建的 Pod，成与渲染集同一形状的行。

    声明的是整台 Pod 的形状（业务容器求和、与 init 取大者）：这些 Pod 没有清单
    可解析，所以没有容器可加，但它们在额度上的记账方式与渲染集里的 Pod 一字不差
    ——同一条求和、同一个 pods 计数，这样"渲染集里少算了一台 Pod"与"运行期多起
    了一台 Pod"在同一处暴露，而不是一处在算式里、一处在注释里。
    """
    rows = []
    for entry in entries or []:
        if not isinstance(entry, dict):
            continue
        rows.append(
            {
                "name": entry.get("name", "?"),
                "kind": "RuntimePod",
                "replicas": int(entry.get("replicas", 1) or 0),
                "requests_cpu": cpu_cores(entry.get("cpuRequest")),
                "requests_mem": mem_bytes(entry.get("memoryRequest")),
                "limits_cpu": cpu_cores(entry.get("cpuLimit")),
                "limits_mem": mem_bytes(entry.get("memoryLimit")),
                # 运行期的 Pod 不滚动：它们起一台、跑完删掉，没有新旧并存的一段。
                "surge": 0,
            }
        )
    return rows


def project(
    docs, nodes, runtime, default_cpu="500m", default_memory="512Mi", pvc_min="1Gi"
):
    rows = declared_workloads(docs, nodes) + runtime
    if not rows:
        raise SystemExit("渲染集里没有工作负载，投影没有输入")

    limits_cpu = sum(r["replicas"] * r["limits_cpu"] for r in rows)
    limits_mem = sum(r["replicas"] * r["limits_mem"] for r in rows)
    requests_cpu = sum(r["replicas"] * r["requests_cpu"] for r in rows)
    requests_mem = sum(r["replicas"] * r["requests_mem"] for r in rows)
    # 一次滚动只有一个 Deployment 在滚：重叠取**最大的一份**，不是求和。
    overlap_cpu = max((r["surge"] * r["limits_cpu"] for r in rows), default=0.0)
    overlap_mem = max((r["surge"] * r["limits_mem"] for r in rows), default=0)
    # 重叠在 requests 这一维同样存在：新 Pod 与旧 Pod 并排站着时，两者的 requests
    # 一起向调度器要位置。只把它算进 limits 会让 requests 的余量恰好为零——那时
    # 额度放得下新 Pod 的 limits，却放不下它自己的 requests，准入拒掉的理由会写在
    # 另一维上，读起来像另一件事。
    overlap_req_cpu = max((r["surge"] * r["requests_cpu"] for r in rows), default=0.0)
    overlap_req_mem = max((r["surge"] * r["requests_mem"] for r in rows), default=0)

    job = deployer_job_size(docs)
    pods_at_rest = sum(r["replicas"] for r in rows)
    storage, largest_pvc = pvc_bytes(docs)
    max_container_cpu, max_container_mem = largest_container(docs)
    # 运行期的 Pod 只声明整台的形状，所以这里拿整台当它的最大容器看：上限只会
    # 因此更宽，不会比它自己那台 Pod 还窄——窄了那台 Pod 在准入被拒。
    for row in runtime:
        max_container_cpu = max(max_container_cpu, row["limits_cpu"])
        max_container_mem = max(max_container_mem, row["limits_mem"])

    return {
        "limitsCpu": fmt_cpu(limits_cpu + job["limits_cpu"] + overlap_cpu),
        "limitsMemory": fmt_mem(limits_mem + job["limits_mem"] + overlap_mem),
        "requestsCpu": fmt_cpu(requests_cpu + job["requests_cpu"] + overlap_req_cpu),
        "requestsMemory": fmt_mem(requests_mem + job["requests_mem"] + overlap_req_mem),
        # Pod 数按两倍常驻算：一次滚动要把新旧两版同时在准入里放一遍，而运维
        # 临时 Pod 与判据 Job 也在同一个额度下。比例而不是绝对值——它跟着
        # 工作负载规模走，不跟着某一台机器的规格走。
        "pods": str(2 * pods_at_rest),
        # 存储留一成头寸：这个额度的作用是拒绝一份总量越界的清单，而声明和与
        # 它恰好相等时，任何一条卷声明调大都要先改额度才装得进去——渲染期门禁
        # 把"头寸为零"判红。一成是余量，不是规格。
        "requestsStorage": f"{math.ceil(storage * 1.1 / (1024**3))}Gi",
        # 上限贴着最大的那份声明：没有更大的声明时，它同时也是 LimitRange 的
        # 默认值能给出的最大尺寸（否则一份「只拿默认值」的容器反而进不来）。
        "maxCpu": fmt_cpu(max(max_container_cpu, cpu_cores(default_cpu))),
        "maxMemory": fmt_mem(max(max_container_mem, mem_bytes(default_memory))),
        "pvcMaxStorage": f"{math.ceil(max(largest_pvc, mem_bytes(pvc_min)) / (1024**3))}Gi",
        "_detail": {
            "limits_cpu_declared": limits_cpu,
            "limits_mem_declared": limits_mem,
            "overlap_cpu": overlap_cpu,
            "overlap_mem": overlap_mem,
            "overlap_req_cpu": overlap_req_cpu,
            "overlap_req_mem": overlap_req_mem,
            "job": job,
            "pods_at_rest": pods_at_rest,
            "storage": storage,
            "rows": rows,
        },
    }


