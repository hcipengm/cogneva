def load_docs(paths):
    docs = []
    for path in paths:
        with open(path) as fh:
            for doc in yaml.safe_load_all(fh):
                if isinstance(doc, dict) and doc.get("kind"):
                    doc["__path__"] = path
                    docs.append(doc)
    return docs


def render_docs(rendered):
    if os.path.isdir(rendered):
        paths = sorted(
            os.path.join(rendered, n) for n in os.listdir(rendered) if n.endswith(".yaml")
        )
    else:
        paths = [rendered]
    return load_docs(paths)


def pod_footprint(spec):
    """一个 Pod 的 (requests.cpu, requests.mem, limits.cpu, limits.mem)。

    与 kubelet 的记账同一口径：业务容器求和，init 容器取最大值，两者再取大者。
    """
    pod = spec.get("template", {}).get("spec") or {}

    def tally(containers):
        cpu_r = cpu_l = 0.0
        mem_r = mem_l = 0
        for c in containers:
            res = c.get("resources") or {}
            req = res.get("requests") or {}
            lim = res.get("limits") or {}
            cpu_r += cpu_cores(req.get("cpu"))
            mem_r += mem_bytes(req.get("memory"))
            cpu_l += cpu_cores(lim.get("cpu"))
            mem_l += mem_bytes(lim.get("memory"))
        return cpu_r, mem_r, cpu_l, mem_l

    (c_r, m_r, c_l, m_l) = tally(pod.get("containers") or [])
    (i_r, im_r, i_l, im_l) = tally(pod.get("initContainers") or [])
    return (
        max(c_r, i_r),
        max(m_r, im_r),
        max(c_l, i_l),
        max(m_l, im_l),
    )


def surge_extra(doc, replicas):
    """一次滚动要多占几份 Pod（maxSurge 的控制器取整口径）。"""
    spec = doc.get("spec") or {}
    strategy = spec.get("strategy") or {}
    if strategy.get("type", "RollingUpdate") != "RollingUpdate":
        return 0
    raw = str((strategy.get("rollingUpdate") or {}).get("maxSurge", "25%"))
    if raw.endswith("%"):
        return int(-(-(float(raw[:-1]) * replicas) // 100))
    return int(raw)


def declared_workloads(docs, nodes):
    """(副本数, Pod 占用, 滚动重叠份数) 的逐对象清单。"""
    rows = []
    for doc in docs:
        kind = doc.get("kind")
        if kind not in ("Deployment", "StatefulSet", "DaemonSet", "Job", "CronJob"):
            continue
        spec = doc.get("spec") or {}
        if kind == "DaemonSet":
            replicas = nodes
        elif kind == "Job":
            replicas = int(spec.get("parallelism") or 1)
        elif kind == "CronJob":
            job = spec.get("jobTemplate", {}).get("spec") or {}
            replicas = int(job.get("parallelism") or 1)
        else:
            replicas = int(spec.get("replicas", 1) or 0)
        pod_spec = spec
        if kind == "CronJob":
            pod_spec = spec.get("jobTemplate", {}).get("spec") or {}
        cpu_r, mem_r, cpu_l, mem_l = pod_footprint(pod_spec)
        surge = surge_extra(doc, replicas) if kind == "Deployment" else 0
        rows.append(
            {
                "name": doc.get("metadata", {}).get("name", "?"),
                "kind": kind,
                "replicas": replicas,
                "requests_cpu": cpu_r,
                "requests_mem": mem_r,
                "limits_cpu": cpu_l,
                "limits_mem": mem_l,
                "surge": surge,
            }
        )
    return rows


def pvc_bytes(docs):
    total = 0
    largest = 0
    for doc in docs:
        kind = doc.get("kind")
        if kind == "PersistentVolumeClaim":
            spec = doc.get("spec") or {}
            want = mem_bytes(
                ((spec.get("resources") or {}).get("requests") or {}).get("storage")
            )
        elif kind == "StatefulSet":
            want = 0
            for tpl in (doc.get("spec") or {}).get("volumeClaimTemplates") or []:
                want += mem_bytes(
                    (((tpl.get("spec") or {}).get("resources") or {}).get("requests") or {}).get(
                        "storage"
                    )
                )
        else:
            continue
        total += want
        largest = max(largest, want)
    return total, largest


def largest_container(docs):
    """全表最大的那份单容器声明：LimitRange 的上限必须 ≥ 它，否则该 Pod 进不来。"""
    cpu = 0.0
    mem = 0
    for doc in docs:
        spec = doc.get("spec") or {}
        if doc.get("kind") == "CronJob":
            spec = spec.get("jobTemplate", {}).get("spec") or {}
        pod = spec.get("template", {}).get("spec") or {}
        for c in (pod.get("containers") or []) + (pod.get("initContainers") or []):
            res = c.get("resources") or {}
            lim = res.get("limits") or {}
            cpu = max(cpu, cpu_cores(lim.get("cpu")))
            mem = max(mem, mem_bytes(lim.get("memory")))
    return cpu, mem


def _find(docs, kind, name):
    for doc in docs:
        if doc.get("kind") == kind and (doc.get("metadata") or {}).get("name") == name:
            return doc
    return None


def deployer_job_size(docs):
    """部署器判据 Job 的尺寸：它在集群里由代码建，声明在进化侧的 configmap 里。"""
    cm = _find(docs, "ConfigMap", "cogneva-evolution-config")
    data = (cm or {}).get("data") or {}
    return {
        "limits_cpu": cpu_cores(data.get("COGNEVA_MAINLINE_DEPLOYER_ROLLOUT_JOB_CPU_LIMIT")),
        "limits_mem": mem_bytes(data.get("COGNEVA_MAINLINE_DEPLOYER_ROLLOUT_JOB_MEMORY_LIMIT")),
        "requests_cpu": cpu_cores(
            data.get("COGNEVA_MAINLINE_DEPLOYER_ROLLOUT_JOB_CPU_REQUEST")
        ),
        "requests_mem": mem_bytes(
            data.get("COGNEVA_MAINLINE_DEPLOYER_ROLLOUT_JOB_MEMORY_REQUEST")
        ),
    }


def project(docs, nodes, default_cpu="500m", default_memory="512Mi", pvc_min="1Gi"):
    rows = declared_workloads(docs, nodes)
    if not rows:
        raise SystemExit("渲染集里没有工作负载，投影没有输入")

    limits_cpu = sum(r["replicas"] * r["limits_cpu"] for r in rows)
    limits_mem = sum(r["replicas"] * r["limits_mem"] for r in rows)
    requests_cpu = sum(r["replicas"] * r["requests_cpu"] for r in rows)
    requests_mem = sum(r["replicas"] * r["requests_mem"] for r in rows)
    # 一次滚动只有一个 Deployment 在滚：重叠取**最大的一份**，不是求和。
    overlap_cpu = max((r["surge"] * r["limits_cpu"] for r in rows), default=0.0)
    overlap_mem = max((r["surge"] * r["limits_mem"] for r in rows), default=0)
    # 重叠在 requests 这一维同样存在：新 Pod 与旧 Pod 并排站着时，两者的 requests
    # 一起向调度器要位置。只把它算进 limits 会让 requests 的余量恰好为零——那时
    # 额度放得下新 Pod 的 limits，却放不下它自己的 requests，准入拒掉的理由会写在
    # 另一维上，读起来像另一件事。
    overlap_req_cpu = max((r["surge"] * r["requests_cpu"] for r in rows), default=0.0)
    overlap_req_mem = max((r["surge"] * r["requests_mem"] for r in rows), default=0)

    job = deployer_job_size(docs)
    pods_at_rest = sum(r["replicas"] for r in rows)
    storage, largest_pvc = pvc_bytes(docs)
    max_container_cpu, max_container_mem = largest_container(docs)

    return {
        "limitsCpu": fmt_cpu(limits_cpu + job["limits_cpu"] + overlap_cpu),
        "limitsMemory": fmt_mem(limits_mem + job["limits_mem"] + overlap_mem),
        "requestsCpu": fmt_cpu(requests_cpu + job["requests_cpu"] + overlap_req_cpu),
        "requestsMemory": fmt_mem(requests_mem + job["requests_mem"] + overlap_req_mem),
        # Pod 数按两倍常驻算：一次滚动要把新旧两版同时在准入里放一遍，而运维
        # 临时 Pod 与判据 Job 也在同一个额度下。比例而不是绝对值——它跟着
        # 工作负载规模走，不跟着某一台机器的规格走。
        "pods": str(2 * pods_at_rest),
        # 存储的头寸见 STORAGE_HEADROOM：它既是「拒绝一份总量越界的清单」的那点余量，
        # 也要把稳态占比压在上游告警阈值之下——稳态 used 就是这里的 storage。
        "requestsStorage": f"{math.ceil(storage * STORAGE_HEADROOM / (1024**3))}Gi",
        # 上限贴着最大的那份声明：没有更大的声明时，它同时也是 LimitRange 的
        # 默认值能给出的最大尺寸（否则一份「只拿默认值」的容器反而进不来）。
        "maxCpu": fmt_cpu(max(max_container_cpu, cpu_cores(default_cpu))),
        "maxMemory": fmt_mem(max(max_container_mem, mem_bytes(default_memory))),
        "pvcMaxStorage": f"{math.ceil(max(largest_pvc, mem_bytes(pvc_min)) / (1024**3))}Gi",
        "_detail": {
            "limits_cpu_declared": limits_cpu,
            "limits_mem_declared": limits_mem,
            "overlap_cpu": overlap_cpu,
            "overlap_mem": overlap_mem,
            "overlap_req_cpu": overlap_req_cpu,
            "overlap_req_mem": overlap_req_mem,
            "job": job,
            "pods_at_rest": pods_at_rest,
            "storage": storage,
            "rows": rows,
        },
    }


