def governance_inputs(values_path, profile_path):
    """算不出来、必须由人声明的那几项，从 chart values 与 profile 里读。

    读的是**声明**，不是渲染产物：`runtimeWorkloads` 是渲染集之外那几台 Pod 的
    形状，`clusterNodes` 是 DaemonSet 逐节点铺开后有几个 Pod——这两项没有任何清单
    能告诉渲染器，所以它们是输入，其余一切都是输出。
    """
    def load(path):
        if not path:
            return {}
        with open(path) as fh:
            return yaml.safe_load(fh) or {}

    merged = {}
    for src in (load(values_path), load(profile_path)):
        gov = src.get("resourceGovernance") if isinstance(src, dict) else None
        if not isinstance(gov, dict):
            continue
        for key, val in gov.items():
            if isinstance(val, dict):
                merged.setdefault(key, {}).update(val)
            else:
                merged[key] = val
    # 键缺失与"声明了 0 台"是两件事：前者说明这份文件不认识投影要读的东西
    # （改了一半、或换了名字），那样算出来的额度会少一整台 Pod 而没有任何提示。
    if "runtimeWorkloads" not in merged:
        raise SystemExit(
            "values 里没有 resourceGovernance.runtimeWorkloads：运行期自建 Pod 的"
            "形状是额度的一项输入，空列表也要写出来（写不出形状=不知道额度该多大）"
        )
    runtime = merged.get("runtimeWorkloads") or []
    limit_range = merged.get("limitRange") or {}
    return {
        "runtime_workloads": runtime,
        "nodes": int(merged.get("clusterNodes", 1) or 1),
        "default_cpu": limit_range.get("defaultCpu", "500m"),
        "default_memory": limit_range.get("defaultMemory", "512Mi"),
        "default_request_cpu": limit_range.get("defaultRequestCpu", "50m"),
        "default_request_memory": limit_range.get("defaultRequestMemory", "64Mi"),
        "min_cpu": limit_range.get("minCpu", "10m"),
        "min_memory": limit_range.get("minMemory", "16Mi"),
        "pvc_min": limit_range.get("pvcMinStorage", "1Gi"),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rendered", required=True, help="渲染产物目录或单个 YAML")
    ap.add_argument(
        "--values", help="chart values.yaml（读 runtimeWorkloads 与 LimitRange 默认值）"
    )
    ap.add_argument("--profile", help="profile values（读 clusterNodes）")
    ap.add_argument("--nodes", type=int)
    ap.add_argument("--write-values")
    ap.add_argument("--write-quota")
    ap.add_argument("--default-cpu")
    ap.add_argument("--default-memory")
    ap.add_argument("--default-request-cpu")
    ap.add_argument("--default-request-memory")
    ap.add_argument("--min-cpu")
    ap.add_argument("--min-memory")
    ap.add_argument("--pvc-min")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    declared = governance_inputs(args.values, args.profile)
    runtime = runtime_rows(declared["runtime_workloads"])
    nodes = args.nodes if args.nodes is not None else declared["nodes"]
    for name in ("default_cpu", "default_memory", "default_request_cpu",
                 "default_request_memory", "min_cpu", "min_memory", "pvc_min"):
        if getattr(args, name) is None:
            setattr(args, name, declared[name])

    docs = render_docs(args.rendered)
    p = project(
        docs,
        nodes,
        runtime,
        default_cpu=args.default_cpu,
        default_memory=args.default_memory,
        pvc_min=args.pvc_min,
    )
    p.update(
        {
            "_runtime_cpu": fmt_cpu(sum(r["replicas"] * r["limits_cpu"] for r in runtime)),
            "_runtime_mem": fmt_mem(sum(r["replicas"] * r["limits_mem"] for r in runtime)),
            "_default_cpu": args.default_cpu,
            "_default_mem": args.default_memory,
            "_default_request_cpu": args.default_request_cpu,
            "_default_request_mem": args.default_request_memory,
            "_min_cpu": args.min_cpu,
            "_min_mem": args.min_memory,
            "_pvc_min": args.pvc_min,
        }
    )

    targets = []
    if args.write_values:
        targets.append((args.write_values, values_document(p)))
    if args.write_quota:
        targets.append((args.write_quota, quota_document(p)))

    if args.check:
        drift = []
        for path, text in targets:
            if not os.path.exists(path):
                drift.append(f"{path}: 不存在（投影产物没生成）")
                continue
            current = open(path).read()
            if current != text:
                drift.append(f"{path}: 与投影不一致（改工作负载后没重新投影，或被人手改了）")
        if drift:
            for line in drift:
                print(f"FAIL: {line}", file=sys.stderr)
            print(
                "      重跑 bash deploy/scripts/render-deploy.sh 会让投影重算并写回。",
                file=sys.stderr,
            )
            return 1
        if not args.quiet:
            print("GOVERNANCE PROJECTION OK：额度与渲染集一致")
        return 0

    for path, text in targets:
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        with open(path, "w") as fh:
            fh.write(text)
    if not args.quiet:
        d = p["_detail"]
        print(
            "GOVERNANCE PROJECTION: "
            f"limits {p['limitsCpu']} 核 / {p['limitsMemory']} "
            f"（渲染集声明和 + 运行期 Pod + Job + 重叠 = "
            f"{p['limitsCpu']}；其中运行期 Pod 占 {p['_runtime_cpu']}），"
            f"requests {p['requestsCpu']} 核 / {p['requestsMemory']}，"
            f"pods {p['pods']}，storage {p['requestsStorage']}"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
