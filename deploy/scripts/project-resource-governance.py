#!/usr/bin/env python3
"""把命名空间额度从渲染集里投影出来，而不是由人写进 values。

为什么是投影而不是标定
----------------------
命名空间额度（ResourceQuota 的 hard、LimitRange 的每容器/每卷上限）不是环境
参数，是**这套清单自己的函数**：容器声明了多大、副本有几个、滚动时同时存在几个
Pod、PVC 声明了多少——额度必须装得下这些，一个字节也不用多。同一条算式在人手
写下来的两份文件里（chart values 与 deploy/k3s 基线）已经漂过两次，漂的形态都是
「工作负载长大了，额度没跟」：准入先拒掉下一次滚动，现场读起来却是「这一版永远
滚不上去」。所以这里把它做成算出来的：输入是渲染集，输出是额度，换一套工作负载
额度自己就变。

渲染集里没有的只有一样：DaemonSet 逐节点铺开后有几分 Pod。节点数不是 chart 里的
一个数，也不是 profile 里的一个数——投影器在**渲染宿主**上从 live cluster 读
（`get nodes` 的条数），并把它记进生成文件首部（`# topology-nodes: N`）。CI 没有
集群，`--check` 就按生成文件里记下的拓扑重算：记录的拓扑与渲染集一起被审阅，
改工作负载没重算会让数漂，改拓扑则必须在一份连得上目标集群的检出上重跑渲染。
没有集群的机器要显式给拓扑（`COGNEVA_NODES=N` 或 `--nodes N`），投影不替它猜
一个 1——猜 1 与真只有 1 个节点在产物上同形。

口径
----
- 每个 Pod 的占用取 `max(Σ 业务容器, max init 容器)`，与 kubelet 的记账一致。
- 副本数：Deployment/StatefulSet 取 `spec.replicas`（缺省 1）；DaemonSet 取
  集群节点数；Job/CronJob 取 `parallelism`（缺省 1）。
- 替换重叠：滚动更新的 Deployment 会同时存在 `maxSurge` 个新 Pod 与旧 Pod，
  额度必须容得下**最大的一份**（滚动一次只有一个 Deployment 在滚）。
- 声明和之外没有任何余量：向上取整到整数核 / 整 GiB 就是那点余量。

用法
----
  python3 project-resource-governance.py --rendered <目录或单个 YAML> \\
      --values deploy/helm/cogneva/values.yaml \\
      --profile deploy/helm/cogneva/profiles/<profile>.yaml \\
      [--write-values FILE] [--write-quota FILE] [--check] \\
      [--nodes N | --nodes-from FILE]

`--values` 与 `--profile` 只提供 LimitRange 策略（那几项是量纲上的下限/默认值，
不是这套清单的函数）。节点数按 `--nodes` > `--nodes-from <生成文件的首部>` >
`COGNEVA_NODES` > live cluster（`COGNEVA_KUBECTL`，默认 `sudo -n k3s kubectl`）
的顺序解析；都拿不到就退 2 并说明怎么给，不猜一个 1。

`--check` 只比不写：目标文件与投影不一致就退 1（渲染新鲜度门禁用它）。
"""

