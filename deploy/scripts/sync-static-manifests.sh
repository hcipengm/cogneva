#!/usr/bin/env bash
# 把 chart 渲染里的两处派生值写回 deploy/k3s 静态清单，或者检查它们还一致。
#
# 用法：
#   bash deploy/scripts/sync-static-manifests.sh          # 写回（render-deploy.sh 渲染完自己调）
#   bash deploy/scripts/sync-static-manifests.sh --check  # 只判：漂移即非零
#
# 为什么要有这条路：`deploy/k3s/` 不是权威源，但它是 parity 基线与集群内 GitOps 拉取端，
# 里面有两块是**渲染出来的**，不是人写的——
#
#   1. `cogneva-json-configmap.yaml` 的 `data["cogneva.json"]`，逐字节等于
#      `deploy/helm/cogneva/files/cogneva.json`（只少结尾那个换行，`|-` 会剥掉它）；
#   2. 每份 Deployment 的 `checksum/config` 注解，等于 chart 按两份配置模板算出来的
#      sha256（`cogneva.configChecksum`），值就落在 `deploy/rendered/k3s-single/` 里；
#   3. 头部写着「GENERATED by deploy/scripts/render-deploy.sh」的那几份，整份逐字节
#      等于 `deploy/rendered/k3s-single/` 里同 kind + 同名的对象；本平台工作负载的
#      `app.kubernetes.io/version` 标签照渲染产物写。它们是渲染产物被抄进
#      静态目录的一份副本，而抄的人只有 header 记得——脚本当时根本不写这里，于是同一份
#      对象有两个出处，谁也不会因为对方变了而红。
#
# 这两块此前靠人抄：改一次配置要记得重渲染、再把 JSON 贴进静态清单、再把四个哈希
# sed 进去。三道门（新鲜度、parity、指纹接线）都只负责**发现**漂移，不负责消除它，
# 于是每次拓扑或配置变更都留一处要靠人记性的工步——忘了就是一处红，而「红在别人
# 的提交里」与「本来就没改」在 CI 上长得一样。这台机器能算出来的值不该由人抄。
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
CHART_JSON="${REPO_ROOT}/deploy/helm/cogneva/files/cogneva.json"
STATIC_CONFIG="${REPO_ROOT}/deploy/k3s/cogneva-json-configmap.yaml"
RENDERED="${REPO_ROOT}/deploy/rendered/k3s-single"

mode="write"
case "${1:-}" in
    "") ;;
    --check) mode="check" ;;
    *) echo "用法：$0 [--check]" >&2; exit 2 ;;
esac

for f in "${CHART_JSON}" "${STATIC_CONFIG}" "${RENDERED}"; do
    [ -e "${f}" ] || { echo "FAIL: 缺 ${f}" >&2; exit 2; }
done

python3 - "${REPO_ROOT}" "${mode}" <<'PYEOF'
import json
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
mode = sys.argv[2]
chart_json = root / "deploy/helm/cogneva/files/cogneva.json"
static_config = root / "deploy/k3s/cogneva-json-configmap.yaml"
static_dir = root / "deploy/k3s"
rendered_dir = root / "deploy/rendered/k3s-single"

try:
    import yaml
except ImportError:
    sys.exit("FAIL: 需要 python3-yaml")

changed = []
problems = []


def write(path, text):
    changed.append(str(path.relative_to(root)))
    if mode == "write":
        path.write_text(text)


# ---- 1. 配置正文：逐字节抄进静态清单的块标量 ----
chart_text = chart_json.read_text()
config_text = static_config.read_text()
block = chart_text[:-1] if chart_text.endswith("\n") else chart_text
# 逐行缩进两格；空行保持空行（YAML 块标量里空行不需要缩进）
indented = "".join(
    ("  " + line.rstrip("\n") + "\n") if line.strip() else line
    for line in block.splitlines(keepends=True)
)
if not indented.endswith("\n"):
    indented += "\n"

head = "  cogneva.json: |-"
lines = config_text.splitlines(keepends=True)
try:
    hi = next(i for i, l in enumerate(lines) if l.rstrip("\r\n") == head)
except StopIteration:
    problems.append("deploy/k3s/cogneva-json-configmap.yaml 里没有 `  cogneva.json: |-` 这个键")
    hi = None

if hi is not None:
    # 块标量的缩进是作者定的（这份清单写的是四格）；照抄它，不自己另定一格。
    indent_len = None
    body_end = len(lines)
    for i in range(hi + 1, len(lines)):
        line = lines[i]
        if not line.strip():
            continue
        cur = len(line) - len(line.lstrip(" "))
        if indent_len is None:
            indent_len = cur
        if cur < indent_len:
            body_end = i
            break
    if indent_len is None:
        problems.append("`cogneva.json: |-` 下面一行内容都没有")
    else:
        pad = " " * indent_len
        body = "".join(
            (pad + l.rstrip("\r\n") + "\n") if l.strip() else l
            for l in block.splitlines(keepends=True)
        )
        new_text = "".join(lines[: hi + 1]) + body + "".join(lines[body_end:])
        # 文件末尾有没有换行是这份清单原来的写法，不是本脚本要改的事。
        if not config_text.endswith("\n") and new_text.endswith("\n"):
            new_text = new_text[:-1]
        if new_text != config_text:
            try:
                doc = yaml.safe_load(new_text)
                ok = json.loads(list(doc["data"].values())[0]) == json.loads(chart_text)
            except Exception as exc:  # noqa: BLE001 - 任何解析失败都是这条路的失败
                ok = False
                problems.append(f"写入后的静态清单解析不出来：{exc}")
            if ok:
                write(static_config, new_text)
            elif not problems:
                problems.append("写入后的静态清单与 chart 的 cogneva.json 解析结果不一致")

# ---- 2. 配置指纹：从渲染产物里按 Deployment 名搬到同名静态清单 ----
rendered_checksums = {}
for yml in sorted(rendered_dir.glob("*.yaml")):
    try:
        for doc in yaml.safe_load_all(yml.read_text()):
            if not isinstance(doc, dict) or doc.get("kind") != "Deployment":
                continue
            name = (doc.get("metadata") or {}).get("name")
            annotations = ((doc.get("spec") or {}).get("template") or {}).get("metadata", {}).get("annotations") or {}
            value = annotations.get("checksum/config")
            if not name or value is None:
                continue
            # 以文本读：一个全是数字的摘要会被 YAML 当成整数（0 就是假值），
            # 按真值判会把它当成「这份工作负载没有指纹」，于是它永远同步不到。
            value = str(value)
            if not re.fullmatch(r"[0-9a-f]{64}", value):
                problems.append(f"{yml.relative_to(root)}：{name} 的 checksum/config 不是 sha256 字面量：{value}")
                continue
            rendered_checksums[name] = value
    except Exception as exc:  # noqa: BLE001
        problems.append(f"{yml.relative_to(root)} 读不出来：{exc}")

seen = set()
for yml in sorted(static_dir.glob("*.yaml")):
    text = yml.read_text()
    if "checksum/config:" not in text:
        continue
    try:
        docs = [d for d in yaml.safe_load_all(text) if isinstance(d, dict)]
    except Exception as exc:  # noqa: BLE001
        problems.append(f"{yml.relative_to(root)} 读不出来：{exc}")
        continue
    for doc in docs:
        if doc.get("kind") != "Deployment":
            continue
        name = (doc.get("metadata") or {}).get("name")
        if name not in rendered_checksums:
            problems.append(
                f"{yml.relative_to(root)} 的 Deployment/{name} 带 checksum/config，"
                f"但 k3s-single 渲染产物里没有对应的 Deployment —— 指纹无从派生"
            )
            continue
        seen.add(name)
        want = rendered_checksums[name]
        new_text, n = re.subn(r"(checksum/config:\s*)[0-9a-f]{64}", r"\g<1>" + want, text, count=1)
        if n != 1:
            problems.append(f"{yml.relative_to(root)}：checksum/config 不是一个 sha256 字面量")
            continue
        if new_text != text:
            write(yml, new_text)

# ---- 3. 头部自称由渲染脚本生成的静态清单：整份对齐渲染产物 ----
# 按 kind + name 找对应对象，不按文件名：静态目录的命名是手写的
# （`process-census-daemonset.yaml`），渲染目录的是 `<序>-<kind>-<name>.yaml`。
rendered_docs = {}
for yml in sorted(rendered_dir.glob("*.yaml")):
    try:
        for doc in yaml.safe_load_all(yml.read_text()):
            if isinstance(doc, dict) and doc.get("kind") and doc.get("metadata", {}).get("name"):
                rendered_docs[(doc["kind"], doc["metadata"]["name"])] = yml
    except Exception:  # noqa: BLE001 - 这一段只读它需要的键，读不出的留给上面那段报
        continue

CLAIM = "GENERATED by deploy/scripts/render-deploy.sh"
for yml in sorted(static_dir.glob("*.yaml")):
    text = yml.read_text()
    if CLAIM not in text:
        continue
    try:
        docs = [d for d in yaml.safe_load_all(text) if isinstance(d, dict) and d.get("kind")]
    except Exception as exc:  # noqa: BLE001
        problems.append(f"{yml.relative_to(root)} 读不出来：{exc}")
        continue
    if len(docs) != 1:
        problems.append(
            f"{yml.relative_to(root)} 自称渲染产物，却装了 {len(docs)} 个对象 —— "
            f"渲染一份文件只写一个对象，这里没法对上"
        )
        continue
    key = (docs[0]["kind"], docs[0]["metadata"]["name"])
    src = rendered_docs.get(key)
    if src is None:
        problems.append(
            f"{yml.relative_to(root)} 自称渲染产物（{key[0]}/{key[1]}），"
            f"但 k3s-single 渲染里没有这个对象 —— 这份没有出处"
        )
        continue
    want_text = src.read_text()
    if want_text != text:
        write(yml, want_text)

# ---- 4. 版本标签：静态清单里本平台工作负载的版本，跟着渲染产物走 ----
# 发布版本的**声明**只有一处（Cargo.toml），chart values 是它的第二份写法，静态清单是
# 第三份。前两份由一致性门比对，第三份此前靠人挨个 sed：一个版本要改 20 个文件里几十
# 行，漏一行就是「这个 Pod 挂的版本号与镜像不是同一个」，而 `kubectl get pods -L
# app.kubernetes.io/version` 那一列看不出来——它是空格，读作「不归发布管」。
#
# 取的是渲染产物里同一个 kind+name 的 Pod 模板标签，不是 Cargo.toml：渲染产物是 chart
# 的读法，静态清单要跟的是它。第三方工作负载（postgres、qdrant…）不在这一步里——它们的
# 版本标签写的是它们自己的版本。
OUR_KINDS = ("Deployment", "DaemonSet", "StatefulSet")
rendered_version = {}
for yml in sorted(rendered_dir.glob("*.yaml")):
    try:
        for doc in yaml.safe_load_all(yml.read_text()):
            if not isinstance(doc, dict) or doc.get("kind") not in OUR_KINDS:
                continue
            name = (doc.get("metadata") or {}).get("name")
            labels = ((doc.get("spec") or {}).get("template") or {}).get("metadata", {}).get("labels") or {}
            value = labels.get("app.kubernetes.io/version")
            if name and value is not None:
                rendered_version[(doc["kind"], name)] = str(value)
    except Exception:  # noqa: BLE001 - 同上：读不出的那份由上面那段点名
        continue

VERSION_KEY = "app.kubernetes.io/version"
NAME_KEY = "app.kubernetes.io/name"
COMPONENT_KEY = "app.kubernetes.io/component"


def indent_of(line):
    return len(line) - len(line.lstrip(" "))


def labels_block_end(lines, start):
    """`labels:` 这一块到哪一行为止（不含）。空行不算结束：块里允许空行。"""
    indent = indent_of(lines[start])
    end = start + 1
    while end < len(lines):
        if not lines[end].strip():
            end += 1
            continue
        if indent_of(lines[end]) <= indent:
            break
        end += 1
    return end


def set_version_in_block(lines, start, want):
    """返回这一块是否改过。有版本行就改值，没有就插在 component/name 之后。"""
    end = labels_block_end(lines, start)
    key_re = re.compile(r"^(\s*)" + re.escape(VERSION_KEY) + r":\s*.*?$")
    changed = False
    found = False
    for k in range(start + 1, end):
        m = key_re.match(lines[k].rstrip("\r\n"))
        if m:
            # 找到了就是找到了：值本来就对时没有改动，但那不等于这一块没有这一行——
            # 按「改没改过」决定要不要插入，会在每一份本来就正确的清单上多插一行。
            found = True
            newline = m.group(1) + VERSION_KEY + ': "' + want + '"'
            if lines[k].rstrip("\r\n") != newline:
                lines[k] = newline + "\n"
                changed = True
    if found:
        return changed
    anchor_at = None
    for k in range(start + 1, end):
        stripped = lines[k].strip()
        if stripped.startswith(COMPONENT_KEY + ":") or stripped.startswith(NAME_KEY + ":"):
            anchor_at = k
            if stripped.startswith(COMPONENT_KEY + ":"):
                break
    if anchor_at is None:
        return False
    pad = " " * indent_of(lines[anchor_at])
    lines.insert(anchor_at + 1, pad + VERSION_KEY + ': "' + want + '"\n')
    return True


for yml in sorted(static_dir.glob("*.yaml")):
    original = yml.read_text()
    lines = original.splitlines(keepends=True)
    # 文档边界按 `---` 切，再逐段解析：整份一起解析会让「第几段」与「第几个对象」对不上，
    # 而这段代码要在**具体那一段**的文本里动手。
    bounds = [(0, len(lines))]
    seps = [i for i, l in enumerate(lines) if re.fullmatch(r"---\s*\r?\n?", l)]
    if seps:
        bounds = []
        start = 0
        for sep in seps:
            bounds.append((start, sep))
            start = sep + 1
        bounds.append((start, len(lines)))
    edited_spans = []
    for start, end in bounds:
        segment = "".join(lines[start:end])
        try:
            doc = yaml.safe_load(segment)
        except Exception:  # noqa: BLE001 - 解析不了的文件由上面那段（或一致性门）点名
            continue
        if not isinstance(doc, dict) or doc.get("kind") not in OUR_KINDS:
            continue
        name = (doc.get("metadata") or {}).get("name")
        labels = ((doc.get("spec") or {}).get("template") or {}).get("metadata", {}).get("labels") or {}
        if not str(labels.get(NAME_KEY, "")).startswith("cogneva"):
            continue
        want = rendered_version.get((doc["kind"], name))
        if want is None:
            continue
        local = lines[start:end]
        touched = False
        i = 0
        while i < len(local):
            if re.fullmatch(r"\s*labels:\s*(#.*)?\r?\n?", local[i]):
                if set_version_in_block(local, i, want):
                    touched = True
                i = labels_block_end(local, i)
                continue
            i += 1
        if touched:
            lines[start:end] = local
            edited_spans.append(local)
    if not edited_spans:
        continue
    new_text = "".join(lines)
    # 写完要能读回来、且读回来的就是想要的那一版：文本手术改坏的清单不能落盘。
    try:
        check = [
            d for d in yaml.safe_load_all(new_text)
            if isinstance(d, dict) and d.get("kind") in OUR_KINDS
        ]
    except Exception as exc:  # noqa: BLE001
        problems.append(f"{yml.relative_to(root)} 写版本标签后解析不出来：{exc}")
        continue
    ok = True
    for doc in check:
        labels = ((doc.get("spec") or {}).get("template") or {}).get("metadata", {}).get("labels") or {}
        want = rendered_version.get((doc["kind"], (doc.get("metadata") or {}).get("name")))
        if want is not None and str(labels.get(VERSION_KEY)) != want:
            ok = False
    if not ok:
        problems.append(f"{yml.relative_to(root)}：写回后版本标签仍与渲染产物不一致")
        continue
    write(yml, new_text)

missing = sorted(set(rendered_checksums) - seen)
if missing:
    # 只提示不判死：静态清单里没有某一份工作负载，是 parity 那道门管的事，不是这条。
    print(f"    （k3s-single 渲染有、静态清单没有 fingerprints 的工作负载：{', '.join(missing)}）")

if problems:
    print("FAIL: 静态清单同步不了：", file=sys.stderr)
    for p in problems:
        print(f"  - {p}", file=sys.stderr)
    sys.exit(1)

if not changed:
    print(f"SYNC STATIC OK（{mode}）：deploy/k3s 的派生部分与 chart 渲染一致")
    sys.exit(0)

if mode == "check":
    print("FAIL: deploy/k3s 的派生部分落后于 chart 渲染：", file=sys.stderr)
    for c in changed:
        print(f"  - {c}", file=sys.stderr)
    print("跑 `bash deploy/scripts/sync-static-manifests.sh` 写回，再一起提交。", file=sys.stderr)
    sys.exit(1)

print(f"SYNC STATIC 写回 {len(changed)} 份：")
for c in changed:
    print(f"  - {c}")
PYEOF
