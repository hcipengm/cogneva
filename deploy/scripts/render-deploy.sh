#!/usr/bin/env bash
# 预渲染部署 profile：Helm chart 为拓扑唯一权威源，本脚本把 chart + profile
# values 渲染成 standalone YAML（deploy/rendered/<profile>/），供元启动
# "读目录 -> kubectl apply" 消费——引导链零 helm 依赖。
#
# 用法：
#   bash deploy/scripts/render-deploy.sh           # 渲染全部 profile，写回 deploy/rendered/
#   bash deploy/scripts/render-deploy.sh --check   # CI 新鲜度门禁：重渲染到临时目录，
#                                                  # 与已提交产物 diff，漂移即失败
#
# 渲染产物是构建产物，不要手改；改拓扑请动 chart templates / values / profile，
# 然后重跑本脚本并一并提交。
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
CHART_DIR="$REPO_ROOT/deploy/helm/cogneva"
PROFILES_DIR="$CHART_DIR/profiles"
RENDERED_DIR="$REPO_ROOT/deploy/rendered"

# profile 的集合是**读出来的**：deploy/helm/cogneva/profiles/ 下的每个 `<名字>.yaml` 就是
# 一个 profile。写死一份名单，新增的那一个会安静地不渲染、不判新鲜度，
# `deploy/rendered/<新名字>/` 也不会出现——下游按目录读 profile 的那几条门（采集器覆盖、
# 读权限载体）于是也看不见它，几处一起空白，而空白读作「本来就没有这个 profile」。
PROFILES=()
for profile_file in "$PROFILES_DIR"/*.yaml; do
    [ -e "$profile_file" ] || continue
    PROFILES+=("$(basename "$profile_file" .yaml)")
done
if [ "${#PROFILES[@]}" -eq 0 ]; then
    echo "FAIL: ${PROFILES_DIR} 下一个 profile 都没有——判不了该渲染哪些，这不等于全过" >&2
    exit 2
fi

# 反向也要比：deploy/rendered/ 下每一棵产物树都得有对应的 profile。删了 profile 却把
# 产物留在树里时，新鲜度门只问「每个 profile 都有产物」，那棵没有出处的树就一直被提交，
# 还被下游按目录读 profile 的门当成一条真的投递路径去判。
require_rendered_trees_have_profiles() {
    [ -d "$RENDERED_DIR" ] || return 0
    local dir name known p stray=0
    for dir in "$RENDERED_DIR"/*/; do
        [ -d "$dir" ] || continue
        name="$(basename "$dir")"
        known=0
        for p in "${PROFILES[@]}"; do
            [ "$p" = "$name" ] && known=1
        done
        if [ "$known" -eq 0 ]; then
            echo "FAIL: deploy/rendered/${name} 没有对应的 profile（profiles/${name}.yaml 不存在）。" >&2
            echo "      这棵树不会有任何东西再渲染它；删掉它，或把 profile 加回来。" >&2
            stray=1
        fi
    done
    [ "$stray" -eq 0 ]
}

# 额度是投影出来的产物，不是 values 里手写的一段：见 project-resource-governance.py
# 的头部。它单独成文件，是因为 values.yaml 里全是人写的注释，而投影要整份重写；
# 又按 profile 各一份，因为同一份清单在不同拓扑下声明的卷与副本并不相同（生产
# profile 不建本地 Retain StorageClass，卷就少一条），投影也就不是同一个数。
generated_values() { echo "$CHART_DIR/values.resource-governance.$1.yaml"; }
# deploy/k3s 的配额清单是 parity 基线兼 GitOps 消费物，与 k3s-single 的投影同源。
QUOTA_BASELINE="$REPO_ROOT/deploy/k3s/resource-quota.yaml"

# `raw` 是"先渲染一遍好让投影有输入"的那一遍：额度还没有，模板里的 required
# 会报错，所以整段治理关掉（额度与 LimitRange 上限都不在工作负载声明里，投影
# 读的东西一分不少）。正式那一遍带 -f 投影产物。
helm_render() {
  local profile="$1" out="$2" mode="${3:-governed}"
  local extra=()
  if [ "$mode" = raw ]; then
    extra=(--set resourceGovernance.enabled=false)
  else
    local gen; gen="$(generated_values "$profile")"
    [ -f "$gen" ] && extra=(-f "$gen")
  fi
  helm template cogneva "$CHART_DIR" \
    -f "$PROFILES_DIR/$profile.yaml" \
    ${extra[@]+"${extra[@]}"} \
    --namespace cogneva \
    > "$out"
}

# 从一次渲染里投影出额度并写回（或只核对）。读的只有工作负载自己的声明与
# chart values 里那两项算不出来的输入。
project_governance() {
  local profile="$1" raw="$2" values_out="$3" quota_out="$4"
  shift 4
  local quota_args=()
  [ -n "$quota_out" ] && quota_args=(--write-quota "$quota_out")
  python3 "$SCRIPT_DIR/project-resource-governance.py" \
    --rendered "$raw" \
    --values "$CHART_DIR/values.yaml" \
    --profile "$PROFILES_DIR/$profile.yaml" \
    --write-values "$values_out" \
    ${quota_args[@]+"${quota_args[@]}"} \
    "$@"
}

render_profile() {
  local profile="$1" out_dir="$2"
  mkdir -p "$out_dir"
  find "$out_dir" -name '*.yaml' -delete
  helm_render "$profile" "$out_dir/.rendered.yaml"
  python3 - "$out_dir/.rendered.yaml" "$out_dir" "$profile" <<'PY'
