    label = re.compile(r"^[a-z0-9]([-a-z0-9]*[a-z0-9])?$")
    for section in ("containers", "initContainers"):
        for c in parsed.get("spec", {}).get("template", {}).get("spec", {}).get(section, []) or []:
            cname = c.get("name", "")
            if not label.match(cname):
                sys.exit(
