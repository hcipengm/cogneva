#!/usr/bin/env python3
"""从 chart 的配置文档生成 `cogneva.example.json`。

chart 的 `files/cogneva.json` 是交付配置**唯一**手改的一份；示例是它的投影，
不是第二份手改源。投影只做三件事，其余逐字照抄（键序也照抄）：

  * 首行的说明改成「这是生成物、源在哪」；
  * `github_integration.repo` 换成占位符，示例不能指向这次安装的真实仓库；
  * 告警规则列表只留 `EXAMPLE_RULES` 点名的十条，展示规则长什么样；
    chart 里那份才是这个部署的完整告警策略。

新增一条规则、改一个键，重跑本脚本，示例会跟着变；不跑，`--check` 判红。
手改 `cogneva.example.json` 同样判红——它不是源。

用法：
  python3 deploy/scripts/gen-example-config.py           # 写回 cogneva.example.json
  python3 deploy/scripts/gen-example-config.py --check   # 只判：已提交的示例是否等于投影
"""

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE = REPO_ROOT / "deploy/helm/cogneva/files/cogneva.json"
TARGET = REPO_ROOT / "cogneva.example.json"

# 示例里保留的告警规则名。选的是通用基础设施告警与自进化产出告警各几条，
# 让人看见 promql / condition / severity / face 的搭配；具体阈值属于部署策略，
# 不随产品发。names 缺失（chart 里被删或被改名）时本脚本判红，而不是悄悄少一条。
EXAMPLE_RULES = [
    "node_disk_usage_high",
    "node_disk_usage_critical",
    "node_disk_pressure",
    "node_memory_pressure",
    "pod_restarting_fast",
    "pod_oom_killed",
    "ralph_loop_terminations_high",
    "declared_failure_class_unrecorded",
    "self_evolution_yields_no_change",
    "cogneva_workload_metrics_unscraped",
]

DESCRIPTION = (
    "GENERATED from deploy/helm/cogneva/files/cogneva.json by "
    "deploy/scripts/gen-example-config.py -- do not edit this file; edit the chart and "
    "re-run the script. The alert rule list keeps ten example rules and "
    "github_integration.repo is a placeholder; every other key is the shipped "
    "configuration. Place this file at /etc/cogneva/cogneva.json or set "
    "COGNEVA_CONFIG_PATH env."
)


def fail(message: str) -> None:
    print(f"FAIL: {message}", file=sys.stderr)
    sys.exit(2)


def missing_path(path: str) -> None:
    fail(
        f"{SOURCE.relative_to(REPO_ROOT)} has no `{path}`: the example cannot be "
        "generated from it. If the key was renamed or removed, update the "
        "projection in this script in the same commit."
    )


def value_at(document: dict, path: str):
    cursor = document
    for segment in path.split("."):
        if not isinstance(cursor, dict) or segment not in cursor:
            missing_path(path)
        cursor = cursor[segment]
    return cursor


def write_at(document: dict, path: str, value) -> None:
    *parents, leaf = path.split(".")
    cursor = document
    for segment in parents:
        if not isinstance(cursor, dict) or segment not in cursor:
            missing_path(path)
        cursor = cursor[segment]
    if not isinstance(cursor, dict) or leaf not in cursor:
        missing_path(path)
    cursor[leaf] = value


def project(source: dict) -> dict:
    # json round-trip keeps the chart's key order, which is the order a reader scans.
    document = json.loads(json.dumps(source))

    write_at(document, "_comment", DESCRIPTION)
    write_at(document, "github_integration.repo", "owner/cogneva")

    rules = value_at(document, "observability.infra_watch.rules")
    names = [rule.get("name") for rule in rules if isinstance(rule, dict)]
    missing = [name for name in EXAMPLE_RULES if name not in names]
    if missing:
        fail(
            "the chart no longer declares these example alert rules: "
            f"{', '.join(missing)}. Update EXAMPLE_RULES in this script in the same "
            "commit as the rule rename/removal."
        )
    kept = [rule for rule in rules if rule.get("name") in EXAMPLE_RULES]
    if len(kept) != len(EXAMPLE_RULES):
        fail(
            f"the chart carries {len(kept)} rules named by EXAMPLE_RULES, expected "
            f"{len(EXAMPLE_RULES)}: a name is duplicated in the chart."
        )
    write_at(document, "observability.infra_watch.rules", kept)
    return document


def rendered(document: dict) -> str:
    return json.dumps(document, ensure_ascii=False, indent=2) + "\n"


def main(argv: list) -> int:
    check = argv[1:] == ["--check"]
    if argv[1:] and not check:
        print("usage: gen-example-config.py [--check]", file=sys.stderr)
        return 2

    try:
        source = json.loads(SOURCE.read_text(encoding="utf-8"))
    except FileNotFoundError:
        fail(f"{SOURCE} does not exist")
    except json.JSONDecodeError as error:
        fail(f"{SOURCE} is not valid JSON: {error}")

    expected = rendered(project(source))

    if check:
        try:
            actual = TARGET.read_text(encoding="utf-8")
        except FileNotFoundError:
            fail(f"{TARGET.relative_to(REPO_ROOT)} does not exist; run this script without --check")
        if actual != expected:
            print(
                f"FAIL: {TARGET.relative_to(REPO_ROOT)} is not the projection of "
                f"{SOURCE.relative_to(REPO_ROOT)}.",
                file=sys.stderr,
            )
            for number, (want, got) in enumerate(
                zip(expected.splitlines(), actual.splitlines()), start=1
            ):
                if want != got:
                    print(f"  first difference at line {number}:", file=sys.stderr)
                    print(f"    generated: {want}", file=sys.stderr)
                    print(f"    committed: {got}", file=sys.stderr)
                    break
            else:
                print("  the two files differ in length only.", file=sys.stderr)
            print(
                "  Run `python3 deploy/scripts/gen-example-config.py` and commit the "
                "result; edit the chart, never the example.",
                file=sys.stderr,
            )
            return 1
        print(f"ok: {TARGET.relative_to(REPO_ROOT)} is the projection of the chart")
        return 0

    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if current == expected:
        print(f"{TARGET.relative_to(REPO_ROOT)} already up to date")
        return 0
    TARGET.write_text(expected, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO_ROOT)} from {SOURCE.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
